  static List<Country>? _cache;

  static String _flag(String code) {
    if (code.length != 2) return '';
    const int base = 0x1F1E6 - 0x41;
    final int a = code.codeUnitAt(0) + base;
    final int b = code.codeUnitAt(1) + base;
    return String.fromCharCodes(<int>[a, b]);
  }

  List<Country> all() {
    final List<Country>? cached = _cache;
    if (cached != null) return cached;
    final List<Country> list = <Country>[
      for (final List<String> r in _raw)
        Country(
          code: r[0],
          name: r[1],
          flagEmoji: _flag(r[0]),
          region: r[2],
        ),
    ]..sort((Country a, Country b) => a.name.compareTo(b.name));
    _cache = List<Country>.unmodifiable(list);
    return _cache!;
  }

  Country? byCode(String code) {
    final String c = code.toUpperCase();
    for (final Country country in all()) {
      if (country.code == c) return country;
    }
    return null;
  }
